import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {build} from 'esbuild';
import Module from 'node:module';
const b=await build({stdin:{contents:`export {chapters} from './src/content';export {getCalculation} from './src/content/calculations';`,resolveDir:process.cwd()},bundle:true,write:false,platform:'node',format:'cjs'});
const m=new Module(`${process.cwd()}/.potential-test.cjs`);m._compile(b.outputFiles[0].text,m.id);
const step=m.exports.chapters.flatMap(c=>c.stages).find(s=>s.id==='ue-potential').lesson.steps.find(s=>s.heading==='微小移動なら掛け算1回に戻る');
assert(step.body.includes('目的：電位の分布Vから'));
assert(step.body.includes('静電場')&&step.body.includes('y,zを固定'));
assert.equal(step.figure,'potential-gradient');
const lines=m.exports.getCalculation(step).lines;
assert(lines[0].tex.includes('\\int'));
const limit=lines.findIndex(l=>l.tex.includes('\\lim'));
const differential=lines.findIndex(l=>l.tex.startsWith('dV='));
assert(limit>0&&differential>limit,'Finite differences must precede differential notation');
assert(!step.body.includes('dxで割って極限'));
const V=x=>4-x*x/2;
for(const h of [1.5,1,.1,.02])assert(Math.abs((V(1)-V(1+h))/h-(1+h/2))<1e-12);
assert.equal(3/3,1);assert.equal(3/1,3);
const drawing=readFileSync('src/components/figures/PotentialGradient.tsx','utf8');
for(const text of ['電位 V [V]','位置 x [m]','粒子の軌道ではありません','ここでは電位差も小さく'])assert(drawing.includes(text));
console.log('PASS: purpose, assumptions, finite-difference order, labels, numerical example');
